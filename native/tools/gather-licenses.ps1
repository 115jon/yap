# Gathers the licence texts an app package ships into one folder:
# THIRD_PARTY_NOTICES.md, Yap's own licence, the texts kept in licenses/
# (Qt, its third-party components, the target's libwebrtc, Apache-2.0,
# MPL-2.0, emoji-mart; see refresh-licenses.ps1), the fonts' and icons'
# licences from assets/, and rust-crates.txt, the licence files of every
# crate the Rust core compiles in, read from cargo's sources.
#
#   ./tools/gather-licenses.ps1 -Out build/licenses                   # desktop
#   ./tools/gather-licenses.ps1 -Out <apk>/assets/licenses `
#       -Manifest mobile/rust/Cargo.toml -CargoTarget aarch64-linux-android
#
# tools/package.ps1 calls it for the Velopack package (licenses\ beside
# Yap.exe) and mobile/CMakeLists.txt for the APK (assets/licenses, read by
# Settings > About > Open source licences). Run it after a build: cargo
# metadata reads the crates from cargo's registry, where the build put them.
param(
    [Parameter(Mandatory)][string]$Out,
    # The Cargo workspace whose crates go into rust-crates.txt.
    [string]$Manifest = "$PSScriptRoot/../rust/Cargo.toml",
    # Only the crates built for this target (cargo metadata --filter-platform).
    [string]$CargoTarget = "x86_64-pc-windows-msvc",
    [string]$Cargo = "cargo"
)
$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$root = (Resolve-Path "$PSScriptRoot/..").Path
$utf8 = [System.Text.UTF8Encoding]::new($false)
if (Test-Path $Out) { Remove-Item -Recurse -Force $Out }
New-Item -ItemType Directory $Out | Out-Null
$Out = (Resolve-Path $Out).Path

Copy-Item "$root/THIRD_PARTY_NOTICES.md" $Out
Copy-Item "$root/../LICENSE" (Join-Path $Out "LICENSE-Yap.txt")
Get-ChildItem "$root/licenses" -File | Where-Object Name -notlike "libwebrtc-*" | Copy-Item -Destination $Out
# The libwebrtc prebuilt's component list differs per platform.
$webrtc = if ($CargoTarget -match "android") { "android" } else { "win" }
Copy-Item "$root/licenses/libwebrtc-$webrtc-LICENSE.md" (Join-Path $Out "libwebrtc-LICENSE.md")
Get-ChildItem "$root/assets/fonts" -Filter "OFL-*.txt" | Copy-Item -Destination $Out
Copy-Item "$root/assets/icons/LICENSE-phosphor.txt" $Out

# rust-crates.txt: every crate reachable from the workspace over normal and
# build dependencies for -CargoTarget, Yap's own crates left out (path
# crates outside rust/vendor, where patches/vendor.ps1 puts the patched
# LiveKit crates).
$json = & $Cargo metadata --format-version 1 --locked --manifest-path $Manifest --filter-platform $CargoTarget
if ($LASTEXITCODE) { throw "cargo metadata failed ($LASTEXITCODE)" }
$meta = $json | ConvertFrom-Json -AsHashtable
$packages = @{}
foreach ($p in $meta.packages) { $packages[$p.id] = $p }
$nodes = @{}
foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
$reached = [System.Collections.Generic.HashSet[string]]::new()
$queue = [System.Collections.Generic.Queue[string]]::new()
foreach ($id in $meta.workspace_members) { if ($reached.Add($id)) { $queue.Enqueue($id) } }
while ($queue.Count -gt 0) {
    $node = $nodes[$queue.Dequeue()]
    if (-not $node) { continue }
    foreach ($dep in $node.deps) {
        # kind is null for a normal dependency, "build" or "dev" otherwise.
        $devOnly = $dep.dep_kinds.Count -gt 0
        foreach ($k in $dep.dep_kinds) { if ($k.kind -ne "dev") { $devOnly = $false } }
        if ($devOnly) { continue }
        if ($reached.Add($dep.pkg)) { $queue.Enqueue($dep.pkg) }
    }
}
$vendor = [System.IO.Path]::GetFullPath("$root/rust/vendor") + [System.IO.Path]::DirectorySeparatorChar
$crates = foreach ($id in $reached) {
    $p = $packages[$id]
    if ($meta.workspace_members -contains $id) { continue }
    $manifestPath = [System.IO.Path]::GetFullPath($p.manifest_path)
    if (-not $p.source -and -not $manifestPath.StartsWith($vendor, [StringComparison]::OrdinalIgnoreCase)) { continue }
    $p
}
$crates = @($crates | Sort-Object { $_.name }, { $_.version })

$licenseName = '^(licen[cs]e|copying|notice|copyright|unlicense|authors)([-_.].*)?$'
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("Rust crates compiled into Yap ($CargoTarget)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Generated by native/tools/gather-licenses.ps1 from cargo metadata and the")
[void]$sb.AppendLine("crates' own sources. Each entry gives the licence the crate's manifest")
[void]$sb.AppendLine("declares and the licence and notice files the crate ships. A text already")
[void]$sb.AppendLine("given above is not repeated. The standard Apache-2.0 and MPL-2.0 texts are")
[void]$sb.AppendLine("also in Apache-2.0.txt and MPL-2.0.txt, for the crates that ship none.")
$seen = @{}
$missing = 0
foreach ($p in $crates) {
    $dir = Split-Path $p.manifest_path -Parent
    $files = @(Get-ChildItem -LiteralPath $dir -File | Where-Object { $_.Name -match $licenseName } | Sort-Object Name)
    # REUSE-style crates keep theirs in LICENSES/.
    if (Test-Path -LiteralPath (Join-Path $dir "LICENSES")) {
        $files += @(Get-ChildItem -LiteralPath (Join-Path $dir "LICENSES") -File | Sort-Object Name)
    }
    if ($p.license_file) {
        $lf = Join-Path $dir $p.license_file
        if ((Test-Path -LiteralPath $lf) -and -not ($files | Where-Object { $_.FullName -eq (Resolve-Path -LiteralPath $lf).Path })) {
            $files += Get-Item -LiteralPath $lf
        }
    }
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine(("=" * 78))
    [void]$sb.AppendLine("$($p.name) $($p.version)")
    $declared = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { "(none declared)" }
    [void]$sb.AppendLine("Licence: $declared")
    if ($p.repository) { [void]$sb.AppendLine("Source: $($p.repository)") }
    if ($files.Count -eq 0) {
        $missing++
        [void]$sb.AppendLine("")
        [void]$sb.AppendLine("(The crate ships no licence file; its manifest declares the licence above.)")
    }
    foreach ($f in $files) {
        $text = [System.IO.File]::ReadAllText($f.FullName)
        $key = ($text -replace '\s+', ' ').Trim()
        [void]$sb.AppendLine("")
        if ($seen.ContainsKey($key)) {
            [void]$sb.AppendLine("($($f.Name): the same text as given for $($seen[$key]) above.)")
        } else {
            $seen[$key] = "$($p.name) $($p.version)"
            [void]$sb.AppendLine("--- $($f.Name) ---")
            [void]$sb.AppendLine($text.TrimEnd())
        }
    }
}
[System.IO.File]::WriteAllText((Join-Path $Out "rust-crates.txt"), $sb.ToString(), $utf8)

$files = @(Get-ChildItem $Out -File)
$kb = [math]::Round((($files | Measure-Object Length -Sum).Sum) / 1KB)
Write-Host "==> licences: $($files.Count) files, $kb KB, $($crates.Count) crates ($missing without a licence file) in $Out"
