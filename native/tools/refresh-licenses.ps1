# Refreshes the third-party licence texts kept in native/licenses/ from the
# sources the apps are built from. Run it by hand when one of them changes
# (a new Qt, a new libwebrtc prebuilt, a new @emoji-mart/data); the build
# never runs it. gather-licenses.ps1 puts these files, the in-repo ones and
# the Rust crates' licences into the packages. THIRD_PARTY_NOTICES.md says
# what each one covers.
#
#   ./tools/refresh-licenses.ps1 -QtSource F:/qt-everywhere-src-6.11.3.zip `
#       -WebrtcLicense <webrtc-win-x64-release>/LICENSE.md `
#       -WebrtcAndroidLicense <android-arm64-release>/LICENSE.md `
#       -EmojiMartTarball emoji-mart-data-1.2.1.tgz
#
# -QtSource is Qt's source release zip (tools/toolchain.lock.json). Its
# LGPL-3.0 and GPL-3.0 texts are copied, and every qt_attribution.json under
# the modules the apps link is turned into Qt-third-party.txt: name,
# version, licence, copyright and the licence file each one names (or, when
# it names none, the module's LICENSES/<id>.txt for its licence id).
# Wayland, X11, macOS, WebAssembly, D-Bus, FFmpeg, SQLite and build-tooling
# attributions are left out: none of that is in the Windows or Android build
# (patches/qt/build-qt.ps1 configures without FFmpeg, SQL and D-Bus; the
# Android app links no Qt Multimedia or Qt SQL).
# -WebrtcLicense and -WebrtcAndroidLicense are the LICENSE.md inside
# LiveKit's prebuilt libwebrtc archives for Windows and Android (WebRTC and
# every component in that prebuilt library; the two lists differ). An
# Android build unpacks its archive under the cargo target folder
# (out/livekit_webrtc/livekit/android-arm64-release-webrtc-*).
# -EmojiMartTarball is `npm pack @emoji-mart/data@<version>`.
param(
    [Parameter(Mandatory)][string]$QtSource,
    [Parameter(Mandatory)][string]$WebrtcLicense,
    [Parameter(Mandatory)][string]$WebrtcAndroidLicense,
    [Parameter(Mandatory)][string]$EmojiMartTarball,
    [string]$Out = "$PSScriptRoot/../licenses"
)
$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest
Add-Type -AssemblyName System.IO.Compression.FileSystem

$modules = @("qtbase", "qtdeclarative", "qtsvg", "qtimageformats", "qtmultimedia", "qtshadertools")
$skip = '/(wayland|xcb|cocoa|wasm|kwin|extra-cmake-modules|gradle|dbus|ffmpeg|sqlite)/'

New-Item -ItemType Directory -Force $Out | Out-Null
$Out = (Resolve-Path $Out).Path
$utf8 = [System.Text.UTF8Encoding]::new($false)

$zip = [System.IO.Compression.ZipFile]::OpenRead((Resolve-Path $QtSource).Path)
try {
    $entries = @{}
    foreach ($e in $zip.Entries) { $entries[$e.FullName] = $e }
    $top = ($zip.Entries[0].FullName -split '/')[0]
    function Read-Entry([string]$path) {
        $e = $entries[$path]
        if (-not $e) { return $null }
        $r = [System.IO.StreamReader]::new($e.Open(), $utf8)
        try { return $r.ReadToEnd() } finally { $r.Dispose() }
    }
    # Folds "a/b/../c" into "a/c" (licence files named relative to the json).
    function Join-ZipPath([string]$dir, [string]$rel) {
        $parts = [System.Collections.Generic.List[string]]::new()
        foreach ($p in (($dir + "/" + $rel) -split '/')) {
            if ($p -eq "..") { $parts.RemoveAt($parts.Count - 1) }
            elseif ($p -ne "." -and $p -ne "") { $parts.Add($p) }
        }
        return ($parts -join '/')
    }

    foreach ($id in @("LGPL-3.0-only", "GPL-3.0-only")) {
        $text = Read-Entry "$top/qtbase/LICENSES/$id.txt"
        if (-not $text) { throw "No qtbase/LICENSES/$id.txt in $QtSource" }
        [System.IO.File]::WriteAllText((Join-Path $Out "Qt-$id.txt"), $text, $utf8)
    }
    # The standard texts for the crates and Maven libraries that ship none
    # of their own (gather-licenses.ps1, THIRD_PARTY_NOTICES.md).
    foreach ($id in @("Apache-2.0", "MPL-2.0")) {
        $text = Read-Entry "$top/qtbase/LICENSES/$id.txt"
        if (-not $text) { throw "No qtbase/LICENSES/$id.txt in $QtSource" }
        [System.IO.File]::WriteAllText((Join-Path $Out "$id.txt"), $text, $utf8)
    }

    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine("Third-party components in Qt $($top -replace '^qt-everywhere-src-','')")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("Generated by native/tools/refresh-licenses.ps1 from the qt_attribution.json")
    [void]$sb.AppendLine("files of $($modules -join ', ') in Qt's source release.")
    [void]$sb.AppendLine("Each entry gives the component's licence and copyright and the licence")
    [void]$sb.AppendLine("text Qt ships with it. A text already given above is not repeated.")
    $seen = @{}
    $jsons = $entries.Keys | Where-Object {
        $_ -match "^$top/($($modules -join '|'))/.*qt_attribution\.json$" -and $_ -notmatch $skip
    } | Sort-Object
    $count = 0
    foreach ($json in $jsons) {
        $raw = Read-Entry $json
        # Some files break a string over lines; JSON does not allow that.
        $raw = [regex]::Replace($raw, '"(?:[^"\\]|\\.)*"', { param($m) $m.Value -replace "\r?\n\s*", " " })
        $items = @($raw | ConvertFrom-Json)
        $dir = Split-Path $json -Parent
        $dir = $dir -replace '\\', '/'
        $module = ($json -split '/')[1]
        foreach ($c in $items) {
            $props = $c.PSObject.Properties.Name
            $name = $c.Name
            $version = if ($props -contains "Version") { $c.Version } else { "" }
            $licenseId = if ($props -contains "LicenseId") { $c.LicenseId } else { "" }
            $license = if ($props -contains "License") { $c.License } else { $licenseId }
            $copyright = if ($props -contains "Copyright") { @($c.Copyright) -join "`n" } else { "" }
            $files = @()
            if ($props -contains "LicenseFile") { $files += @($c.LicenseFile) }
            if ($props -contains "LicenseFiles") { $files += @($c.LicenseFiles) }
            $texts = @()
            foreach ($f in $files) {
                $p = Join-ZipPath $dir $f
                $t = Read-Entry $p
                if ($null -eq $t) { throw "$json names $f, which is not in the source ($p)" }
                $texts += , @($f, $t)
            }
            if ($texts.Count -eq 0 -and $licenseId) {
                foreach ($lid in ($licenseId -split '\s+(?:OR|AND|WITH)\s+|[()]' | Where-Object { $_ })) {
                    $t = Read-Entry "$top/$module/LICENSES/$lid.txt"
                    if ($null -eq $t) {
                        $any = $entries.Keys | Where-Object { $_ -like "$top/*/LICENSES/$lid.txt" } | Select-Object -First 1
                        if ($any) { $t = Read-Entry $any }
                    }
                    if ($null -eq $t) {
                        Write-Warning "$json ($name): Qt's source has no LICENSES/$lid.txt"
                        $t = "(Qt's source release carries no text for $lid; see https://spdx.org/licenses/$lid.html)"
                    }
                    $texts += , @("$lid.txt", $t)
                }
            }
            [void]$sb.AppendLine("")
            [void]$sb.AppendLine(("=" * 78))
            [void]$sb.AppendLine("$name$(if ($version) { " $version" })")
            [void]$sb.AppendLine("Licence: $license$(if ($licenseId -and $licenseId -ne $license) { " ($licenseId)" })")
            if ($copyright) { [void]$sb.AppendLine($copyright) }
            foreach ($pair in $texts) {
                $key = ($pair[1] -replace '\s+', ' ').Trim()
                [void]$sb.AppendLine("")
                if ($seen.ContainsKey($key)) {
                    [void]$sb.AppendLine("($($pair[0]): the same text as given for $($seen[$key]) above.)")
                } else {
                    $seen[$key] = $name
                    [void]$sb.AppendLine("--- $($pair[0]) ---")
                    [void]$sb.AppendLine($pair[1].TrimEnd())
                }
            }
            $count++
        }
    }
    [System.IO.File]::WriteAllText((Join-Path $Out "Qt-third-party.txt"), $sb.ToString(), $utf8)
    Write-Host "==> Qt: $count components from $($jsons.Count) attribution files"
} finally {
    $zip.Dispose()
}

# gather-licenses.ps1 ships the target's one as libwebrtc-LICENSE.md.
Copy-Item $WebrtcLicense (Join-Path $Out "libwebrtc-win-LICENSE.md")
Copy-Item $WebrtcAndroidLicense (Join-Path $Out "libwebrtc-android-LICENSE.md")

# package/LICENSE out of the npm tarball (System.Formats.Tar: PowerShell 7.4+).
$gz = [System.IO.Compression.GZipStream]::new([System.IO.File]::OpenRead((Resolve-Path $EmojiMartTarball).Path),
    [System.IO.Compression.CompressionMode]::Decompress)
try {
    $tar = [System.Formats.Tar.TarReader]::new($gz)
    $found = $false
    while ($entry = $tar.GetNextEntry()) {
        if ($entry.Name -eq "package/LICENSE") {
            $entry.ExtractToFile((Join-Path $Out "emoji-mart-data-LICENSE.txt"), $true)
            $found = $true
            break
        }
    }
    if (-not $found) { throw "No package/LICENSE in $EmojiMartTarball" }
} finally {
    $gz.Dispose()
}
Write-Host "==> $Out"
